package com.xiaozhi.storage.service;

/**
 * 统计库里还有多少条文件地址指向当前生效的对象存储。
 * <p>
 * 库里只存地址、不存「这个文件当初存在哪儿」，也没有迁移机制：换掉对象存储之后，
 * 老地址的 host 不再属于新存储，既签不出临时 URL 也下载不到，历史内容会永久打不开。
 * 换存储之前先用本接口把受影响的条数数出来，交给用户决定要不要继续。
 */
public interface StorageReferenceService {

    /**
     * 统计当前生效的对象存储上的历史引用条数（对话录音）。
     * <p>
     * 当前生效的是本地存储时没有地址前缀可比，历史相对路径也不会因为换存储而失效，恒返回 0；
     * 当前配置已经坏到建不出客户端时同样返回 0，把改回可用配置的路留着。
     */
    long countOnCurrentStorage();
}
